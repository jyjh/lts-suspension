%% ---- 2. Interface (contract item 1) -------------------------------------

function testManagerSubclassesSuspensionComponent(testCase)
mc = meta.class.fromName( ...
    'lts.components.Suspension.SuspensionManager');
supers = {mc.SuperclassList.Name};
verifyTrue(testCase, ...
    any(endsWith(supers, 'SuspensionComponent')), ...
    'SuspensionManager must subclass SuspensionComponent.');
end

function testManagerSatisfiesChassisStructuralProbes(testCase)
% SimpleChassis.setSuspension gates on these structural capabilities —
% no class-name coupling in either direction.
vm = struct('totalMass', 264, 'wheelbase', 1.558, 'trackWidth', 1.21, ...
    'cgHeight', 0.30, 'staticFrontWeight', 0.5038, 'g', 9.80665);
mgr = lts.components.Suspension.SuspensionManager(vm, ...
    43780, 3500, 4000, 39400, 3200, 3600, 1.0, ...
    0.03, 350000, 190000, 9.3);
probes = {'getAxleRollStiffness', 'warmup', ...
    'computeCornerLoadsFromChassis', 'computePitchAngle', ...
    'getCornerKinematics'};
for i = 1:numel(probes)
    verifyTrue(testCase, ismethod(mgr, probes{i}), ...
        sprintf('SuspensionManager must implement %s.', probes{i}));
end
end

%% ---- 3. Telemetry producer fields (contract item 3) ---------------------

function testSuspensionStatePinsTelemetryFieldNames(testCase)
% Exact property names StateLogBuilder maps onto per-corner channels
% (damperPos_FL <- damperPosition, damperVel_FL <- damperVelocity,
% camber_FL <- camberAngle, Fz_FL <- tireNormalForce, ...).
mc = meta.class.fromName('lts.components.Suspension.SuspensionState');
props = {mc.PropertyList.Name};
required = {'damperPosition', 'damperVelocity', 'tireDeflection', ...
    'sprungPosition', 'sprungVelocity', ...
    'unsprungPosition', 'unsprungVelocity', ...
    'wheelTravel', 'camberAngle', 'toeAngle', 'steerAngle', ...
    'tireNormalForce', 'suspensionForce', 'antiRollBarForce', ...
    'demandedLoad'};
for i = 1:numel(required)
    verifyTrue(testCase, ismember(required{i}, props), ...
        sprintf('SuspensionState must keep property %s.', required{i}));
end
end

function testManagerCornerPropertyNamesPinned(testCase)
% StateLogBuilder reaches the per-corner state through exactly these
% property names (mapped to telemetry corners FL/FR/RL/RR).
mc = meta.class.fromName( ...
    'lts.components.Suspension.SuspensionManager');
props = {mc.PropertyList.Name};
required = {'frontLeft', 'frontRight', 'rearLeft', 'rearRight'};
for i = 1:numel(required)
    verifyTrue(testCase, ismember(required{i}, props), ...
        sprintf('SuspensionManager must keep corner property %s.', ...
        required{i}));
end
end
