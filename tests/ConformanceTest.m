        'maxWheelSteerAngle', 0.6));
end

%% ---- 1. Config schema --------------------------------------------------

function testValidateConfigAcceptsCanonicalConfig(testCase)
verifyTrue(testCase, ...
    lts.components.Suspension.validateConfig(canonicalConfig()));
end

function testValidateConfigRejectsMissingArbField(testCase)
cfg = canonicalConfig();
cfg.rearArb = rmfield(cfg.rearArb, 'leverArm');
verifyError(testCase, ...
    @() lts.components.Suspension.validateConfig(cfg), ...
    'lts_suspension_validateConfig:MissingField');
end

