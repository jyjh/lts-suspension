function tests = ConformanceTest
% CONFORMANCETEST Pin the contract between this repository and the main
% lts repository (contract items 1-3 of the repository split; see the
% Contracts page of the main repository's documentation).
%
%  1. cfg schema — lts.components.Suspension.validateConfig accepts the
%     canonical cfg.suspension and rejects bad input with typed errors.
%  2. Interface — SuspensionManager subclasses SuspensionComponent and
%     satisfies the structural probes SimpleChassis performs.
%  3. Telemetry producer fields — the SuspensionState property names
%     below are mapped 1:1 onto per-corner telemetry channels by the
%     main repository's StateLogBuilder. Renaming any of them is a
%     contract change: update this test and the Contracts page in the
%     same PR, then coordinate the main-repository change (see
%     "Changing the contract" there).
tests = functiontests(localfunctions);
end

