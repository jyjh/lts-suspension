    'front', struct('springRate', 45000, 'dampingCoeff', 3000, ...
    'reboundCoeff', 4500), ...
    'rear',  struct('springRate', 42000, 'dampingCoeff', 2800, ...
    'reboundCoeff', 4200), ...
    'motionRatio', 0.95, ...
    'bumpStopLength', 0.025, ...
    'bumpStopRate', 200000, ...
    'tireSpringRate', 200000, ...
    'dampingKneeSpeed', 0.05, ...
    'dampingHighSpeedRatio', 0.3, ...
    'dampingReboundKneeSpeed', NaN, ...
    'frontArb', struct('stiffness', 1800, 'motionRatio', 0.95, ...
    'leverArm', 0.26, 'enabled', true), ...
    'rearArb',  struct('stiffness', 1100, 'motionRatio', 0.95, ...
    'leverArm', 0.26, 'enabled', true), ...
    'rollStiffnessOverride', NaN, ...
